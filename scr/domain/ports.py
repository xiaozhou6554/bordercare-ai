from __future__ import annotations

from typing import Any, Protocol


class CachePort(Protocol):
    def get(self, key: str) -> Any | None: ...
    def set(self, key: str, value: Any, ttl_seconds: int) -> None: ...
    def delete(self, key: str) -> None: ...
    def set_if_absent(self, key: str, value: Any, ttl_seconds: int) -> bool: ...


class SessionMemoryPort(Protocol):
    def load(self, session_id: str) -> dict[str, Any]: ...
    def save_turn(self, session_id: str, user_text: str, assistant_text: str, marketplace: str) -> None: ...
    def clear(self, session_id: str) -> None: ...


class LanguageModelPort(Protocol):
    def complete(self, system: str, prompt: str, temperature: float = 0.2) -> str: ...


class MarketDataPort(Protocol):
    """Data boundary. Demo adapters must identify samples as non-live."""
    def fetch(self, kind: str, keyword: str, marketplace: str, params: dict[str, Any]) -> dict[str, Any]: ...
